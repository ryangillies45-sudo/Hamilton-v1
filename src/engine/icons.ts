// 12x12 stat icons (original pixel art). '#' = main colour, '+' = highlight.
import {C, FB} from './fb';

const ICONS: Record<string, string[]> = {
	trophy: [
		'............', '.##########.', '#+########.#', '#.#+######.#', '.##+######..', '...+#####...',
		'....####....', '.....##.....', '.....##.....', '....####....', '...######...', '...######...',
	],
	podium: [
		'............', '....####....', '....#++#....', '....#..#....', '#####..#....', '#++##..#####',
		'#..##..##++#', '#..##..##..#', '#..##..##..#', '#..##..##..#', '############', '............',
	],
	pole: [
		'.#..........', '.#########..', '.#+#+#+#+#..', '.##+#+#+##..', '.#+#+#+#+#..', '.#########..',
		'.#..........', '.#..........', '.#..........', '.#..........', '.#..........', '###.........',
	],
	star: [
		'.....##.....', '.....##.....', '....####....', '############', '.##########.', '..########..',
		'...######...', '...######...', '..###..###..', '..##....##..', '.##......##.', '............',
	],
	points: [
		'....####....', '..##++++##..', '.#++####++#.', '.#+#....#+#.', '#+#..##..#+#', '#+#.#..#.#+#',
		'#+#.#..#.#+#', '#+#..##..#+#', '.#+#....#+#.', '.#++####++#.', '..##++++##..', '....####....',
	],
};

export const icon = (fb: FB, name: keyof typeof ICONS | string, x: number, y: number, color: string, hi = '#ffffff') => {
	const rows = ICONS[name];
	if (!rows) return;
	const c = C(color), h = C(hi);
	for (let yy = 0; yy < 12; yy++)
		for (let xx = 0; xx < 12; xx++) {
			const ch = rows[yy][xx];
			if (ch === '#') fb.pset(x + xx, y + yy, c);
			else if (ch === '+') fb.pset(x + xx, y + yy, h);
		}
};
